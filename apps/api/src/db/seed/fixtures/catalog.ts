/** Più voci della stessa sotto-categoria. */
function voci(
	macro: string,
	sub: string,
	names: readonly string[],
	skip?: readonly string[],
): CatalogEntry[] {
	return names.map((name) =>
		skip ? { name, macro, sub, skip } : { name, macro, sub },
	);
}

